-- ===== db/migrations/001_init.sql =====
-- Cost Seg Trust: initial schema
-- Works on any Postgres 14+ (Supabase, Neon, RDS). The app connects with a
-- server-side connection string only; nothing here is exposed to browsers.

create extension if not exists pgcrypto;
create extension if not exists citext;

-- Deal stages mirror the HubSpot pipeline one-to-one.
do $$ begin
  create type deal_stage as enum (
    'new_request', 'waiting_on_quotes', 'quotes_received', 'comparison_ready',
    'awaiting_approval', 'sent_to_client', 'closed'
  );
exception when duplicate_object then null; end $$;

do $$ begin
  create type closed_outcome as enum ('won', 'lost');
exception when duplicate_object then null; end $$;

-- One row per person who requests quotes. Email is the dedupe key, matching
-- how HubSpot dedupes contacts.
create table if not exists clients (
  id                 uuid primary key default gen_random_uuid(),
  email              citext not null unique,
  first_name         text not null,
  last_name          text not null default '',
  phone              text,
  hubspot_contact_id text unique,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

create sequence if not exists deal_number_seq start 1001;

create table if not exists deals (
  id                    uuid primary key default gen_random_uuid(),
  number                integer not null unique default nextval('deal_number_seq'),
  -- Generated by the browser for each form load; a double-click or retry
  -- with the same key never creates a second deal.
  request_key           uuid not null unique,
  client_id             uuid not null references clients(id),
  stage                 deal_stage not null default 'new_request',
  closed_outcome        closed_outcome,
  property_address      text not null,
  property_city_state   text,
  property_type         text not null,
  purchase_price        numeric(14,2) not null check (purchase_price > 0),
  placed_in_service     date not null,
  land_value            text,
  renovation_spend      numeric(14,2),
  has_cpa               boolean,
  client_notes          text,
  consent_contact       boolean not null,
  consent_at            timestamptz not null,
  utm_source            text,
  utm_medium            text,
  utm_campaign          text,
  admin_notes           text,
  hubspot_deal_id       text unique,
  hubspot_sync_status   text not null default 'pending' check (hubspot_sync_status in ('pending','synced','failed','skipped')),
  hubspot_synced_at     timestamptz,
  hubspot_error         text,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);
create index if not exists deals_stage_idx on deals(stage);
create index if not exists deals_created_idx on deals(created_at desc);

-- Audit trail shown on the deal page.
create table if not exists deal_events (
  id          bigserial primary key,
  deal_id     uuid not null references deals(id) on delete cascade,
  kind        text not null,
  detail      jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);
create index if not exists deal_events_deal_idx on deal_events(deal_id, created_at);

-- Every email/SMS the system tries to send, with its result.
create table if not exists notifications (
  id           bigserial primary key,
  deal_id      uuid references deals(id) on delete cascade,
  channel      text not null check (channel in ('email','sms')),
  recipient    text not null,
  purpose      text not null,
  status       text not null check (status in ('sent','failed','skipped')),
  provider_id  text,
  error        text,
  created_at   timestamptz not null default now()
);

create table if not exists suppliers (
  id            uuid primary key default gen_random_uuid(),
  company_name  text not null,
  contact_name  text,
  email         citext not null unique,
  phone         text,
  description   text,
  is_test       boolean not null default false,
  active        boolean not null default true,
  notes         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Stage 2 (supplier quoting). Created now so the structure is complete.
-- Suppliers reach their invite through a personalized link; only a SHA-256
-- hash of the token is stored.
create table if not exists supplier_invites (
  id              uuid primary key default gen_random_uuid(),
  deal_id         uuid not null references deals(id) on delete cascade,
  supplier_id     uuid not null references suppliers(id),
  token_hash      text not null unique,
  status          text not null default 'invited' check (status in ('invited','viewed','submitted','declined','expired')),
  invited_at      timestamptz not null default now(),
  due_at          timestamptz not null default now() + interval '40 hours',
  reminder_sent_at timestamptz,
  viewed_at       timestamptz,
  responded_at    timestamptz,
  unique (deal_id, supplier_id)
);

create table if not exists supplier_quotes (
  id                         uuid primary key default gen_random_uuid(),
  invite_id                  uuid not null unique references supplier_invites(id) on delete cascade,
  fee                        numeric(12,2),
  study_type                 text,
  site_visit                 boolean,
  turnaround_days            integer,
  reclassified_pct           numeric(5,2),
  est_first_year_deduction   numeric(14,2),
  est_first_year_tax_savings numeric(14,2),
  assumed_tax_rate           numeric(5,2),
  audit_support              text,
  includes_lookback          boolean,
  payment_terms              text,
  valid_days                 integer,
  comments                   text,
  proposal_file_path         text,
  ai_extracted               jsonb,
  ai_filled_fields           text[] not null default '{}',
  submitted_at               timestamptz not null default now()
);

-- Stage 3 (AI comparison + approval).
create table if not exists comparisons (
  id             uuid primary key default gen_random_uuid(),
  deal_id        uuid not null unique references deals(id) on delete cascade,
  status         text not null default 'draft' check (status in ('draft','approved','sent')),
  summary        text,
  hidden_rows    text[] not null default '{}',
  hidden_invites uuid[] not null default '{}',
  overrides      jsonb not null default '{}'::jsonb,
  anonymize      boolean not null default false,
  approved_at    timestamptz,
  sent_at        timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

-- Small key/value store (e.g. cached HubSpot pipeline and stage ids).
create table if not exists app_settings (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);

create or replace function touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

do $$
declare t text;
begin
  foreach t in array array['clients','deals','suppliers','comparisons'] loop
    execute format('drop trigger if exists %I_touch on %I', t, t);
    execute format('create trigger %I_touch before update on %I for each row execute function touch_updated_at()', t, t);
  end loop;
end $$;

-- Supabase exposes the public schema through its REST API to the "anon" and
-- "authenticated" roles. This app never uses that API, so lock every table
-- with row level security and no policies: only the server connection
-- (table owner) can read or write.
do $$
declare t text;
begin
  foreach t in array array['clients','deals','deal_events','notifications','suppliers','supplier_invites','supplier_quotes','comparisons','app_settings'] loop
    execute format('alter table %I enable row level security', t);
  end loop;
end $$;

-- ===== db/migrations/002_suppliers_ai_reports.sql =====
-- Phases 5-7: supplier responses, AI standardization, comparison approval, PDF reports.

alter table deals add column if not exists quotes_window_closed_at timestamptz;

-- Supplier invites: count link re-sends; "late" is derived from responded_at > due_at.
alter table supplier_invites add column if not exists link_sent_count integer not null default 0;
alter table supplier_invites add column if not exists decline_reason text;
-- When a link is re-issued (reminder or resend), the previous link keeps working too.
alter table supplier_invites add column if not exists previous_token_hash text;
create index if not exists supplier_invites_prev_token_idx on supplier_invites(previous_token_hash);
create index if not exists supplier_invites_pending_idx on supplier_invites(status, due_at) where status in ('invited','viewed');

-- Supplier responses: the uploaded proposal is kept in the database (max 4 MB),
-- plus what the AI read from it.
alter table supplier_quotes drop column if exists proposal_file_path;
alter table supplier_quotes add column if not exists proposal_pdf bytea;
alter table supplier_quotes add column if not exists proposal_filename text;
alter table supplier_quotes add column if not exists ai_status text not null default 'skipped'
  check (ai_status in ('pending','done','failed','skipped'));
alter table supplier_quotes add column if not exists ai_error text;
alter table supplier_quotes add column if not exists ai_mismatches jsonb not null default '[]'::jsonb;
alter table supplier_quotes add column if not exists ai_notes jsonb not null default '{}'::jsonb;

-- Comparison approval flow: draft -> awaiting_approval -> sent.
alter table comparisons drop constraint if exists comparisons_status_check;
alter table comparisons add constraint comparisons_status_check check (status in ('draft','awaiting_approval','sent'));
alter table comparisons add column if not exists client_message text;
alter table comparisons add column if not exists summary_source text;

-- Every generated one-pager PDF, newest version last.
create table if not exists pdf_reports (
  id            uuid primary key default gen_random_uuid(),
  deal_id       uuid not null references deals(id) on delete cascade,
  comparison_id uuid not null references comparisons(id) on delete cascade,
  version       integer not null,
  filename      text not null,
  pdf           bytea not null,
  created_at    timestamptz not null default now(),
  sent_at       timestamptz,
  sent_to       text,
  unique (comparison_id, version)
);
alter table pdf_reports enable row level security;

