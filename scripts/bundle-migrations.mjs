// Packs db/migrations/*.sql (and the test-supplier seed) into
// lib/migrations.generated.ts so the deployed app can set up its own
// database on startup. Runs automatically before `next build`.
import fs from "node:fs";
import path from "node:path";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const read = (dir) => fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith(".sql")).sort()
  .map(f => ({ name: f, sql: fs.readFileSync(path.join(root, dir, f), "utf8") }));
const all = [...read("db/migrations"), ...read("db/seed").map(m => ({ ...m, name: `seed_${m.name}` }))];
const out = `// Generated by scripts/bundle-migrations.mjs from db/migrations and db/seed. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(all, null, 2)};\n`;
const file = path.join(root, "lib", "migrations.generated.ts");
if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== out) fs.writeFileSync(file, out);
